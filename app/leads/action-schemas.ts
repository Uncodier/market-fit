import { z } from "zod"

// Definir el schema de respuesta
export const LeadSchema = z.object({
  leads: z.array(z.object({
    id: z.string(),
    buyer_user_id: z.string().nullable().optional(),
    name: z.string(),
    email: z.string(),
    personal_email: z.string().nullable(),
    phone: z.string().nullable(),
    company: z.object({
      name: z.string().optional(),
      website: z.string().optional(),
      industry: z.string().optional(),
      size: z.string().optional(),
      annual_revenue: z.string().optional(),
      founded: z.string().optional(),
      description: z.string().optional(),
      address: z.object({
        street: z.string().optional(),
        city: z.string().optional(),
        state: z.string().optional(),
        zipcode: z.string().optional(),
        country: z.string().optional(),
      }).optional(),
    }).nullable(),
    company_id: z.string().nullable(),
    position: z.string().nullable(),
    segment_id: z.string().nullable(),
    campaign_id: z.string().nullable(),
    status: z.enum(["new", "contacted", "qualified", "cold", "converted", "lost", "not_qualified"]),
    notes: z.string().nullable(),
    origin: z.string().nullable(),
    created_at: z.string(),
    updated_at: z.string(),
    last_contact: z.string().nullable(),
    site_id: z.string(),
    user_id: z.string(),
    birthday: z.string().nullable(),
    language: z.string().nullable(),
    social_networks: z.object({
      linkedin: z.string().optional().nullable(),
    twitter: z.string().optional().nullable(),
    facebook: z.string().optional().nullable(),
    instagram: z.string().optional().nullable(),
    tiktok: z.string().optional().nullable(),
    youtube: z.string().optional().nullable(),
    whatsapp: z.string().optional().nullable(),
    pinterest: z.string().optional().nullable(),
    threads: z.string().optional().nullable(),
  }).nullable(),
    address: z.object({
      street: z.string().optional(),
      city: z.string().optional(),
      state: z.string().optional(),
      zipcode: z.string().optional(),
      country: z.string().optional(),
    }).nullable(),
    attribution: z.object({
      user_id: z.string(),
      user_name: z.string(),
      date: z.string(),
      final_amount: z.number().optional(),
      is_market_fit_influenced: z.boolean(),
      notes: z.string().optional(),
    }).nullable().optional(),
    assignee_id: z.string().nullable().optional(),
  })).nullable(),
  error: z.string().optional()
})

export type LeadResponse = z.infer<typeof LeadSchema>
