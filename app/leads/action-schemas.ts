// Schema para validar los datos de entrada al crear un lead
export const CreateLeadSchema = z.object({
  name: z.string().min(1, "Name is required").optional().or(z.literal("")),
  email: z.string().email("Invalid email address").optional().nullable().or(z.literal("")),
  personal_email: z.string().email("Invalid personal email address").optional().nullable().or(z.literal("")),
  phone: z.string().optional().nullable().or(z.literal("")),
  company: z.union([
    z.string(),
    z.object({
      name: z.string().optional(),
      website: z.string().optional(),
      industry: z.string().optional(),
      size: z.string().optional(),
      annual_revenue: z.string().optional(),
      founded: z.string().optional(),
      description: z.string().optional(),
      domain: z.string().optional(),
      location: z.any().optional(), // Allow any location structure
      external_organization_id: z.union([z.string(), z.number()]).optional(),
      address: z.object({
        street: z.string().optional(),
        city: z.string().optional(),
        state: z.string().optional(),
        zipcode: z.string().optional(),
        country: z.string().optional(),
      }).optional(),
    }).passthrough(), // Allow additional fields but ignore them during validation
  ]).optional().nullable(),
  company_id: z.string().optional(),
  position: z.string().optional(),
  segment_id: z.string().optional(),
  status: z.enum(["new", "contacted", "qualified", "cold", "converted", "lost", "not_qualified"]).default("new"),
  notes: z.string().optional(),
  origin: z.string().optional(),
  site_id: z.string().min(1, "Site ID is required"),
  birthday: z.string().optional(),
  language: z.string().optional(),
  social_networks: z.object({
    linkedin: z.string().optional().nullable(),
    twitter: z.string().optional().nullable(),
    facebook: z.string().optional().nullable(),
    instagram: z.string().optional().nullable(),
    tiktok: z.string().optional().nullable(),
    youtube: z.string().optional().nullable(),
    whatsapp: z.string().optional().nullable(),
    pinterest: z.string().optional().nullable(),
    threads: z.string().optional().nullable(),
  }).optional(),
  address: z.object({
    street: z.string().optional(),
    city: z.string().optional(),
    state: z.string().optional(),
    zipcode: z.string().optional(),
    country: z.string().optional(),
  }).optional(),
  assignee_id: z.string().optional().nullable(),
  buyer_user_id: z.string().optional().nullable(),
})

export type CreateLeadInput = z.infer<typeof CreateLeadSchema>

