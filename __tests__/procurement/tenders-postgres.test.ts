/** @jest-environment node */
import { actors, ids, isolatedPostgres, postgresAvailable, uuid, actorSql } from './storage-fixture'
import { installTendersFixture, saveTender, tenderDocument, materialize, supplierId } from './tenders-fixture'
import { saveRequest } from './requests-fixture'

jest.setTimeout(180000)
;(postgresAvailable ? describe : describe.skip)('tenders in isolated PostgreSQL', () => {
  const pg = isolatedPostgres()
  beforeAll(() => pg.start())
  afterAll(() => pg.stop())
  beforeEach(() => installTendersFixture(pg))
  const publicRows = (site: string | null = null, tender: string | null = null) => JSON.parse(pg.call(`SELECT COALESCE(jsonb_agg(t),'[]') FROM public.public_procurement_tenders(${site ? `'${site}'` : 'NULL'},${tender ? `'${tender}'` : 'NULL'}) t;`, ids.owner, 'anon'))
  test('creates, edits with CAS and deletes drafts while retaining audit', () => {
    const id = pg.call(saveTender())
    expect(pg.call(`SELECT net_amount_minor FROM public.procurement_tenders WHERE id='${id}';`)).toBe('125000')
    pg.call(saveTender(id, 1, { ...tenderDocument, title: 'New title' }))
    expect(() => pg.call(saveTender(id, 1))).toThrow(/Version/)
    pg.call(`SELECT public.transition_procurement_tender('${ids.site}','${id}',2,'delete');`)
    expect(pg.call('SELECT count(*) FROM public.procurement_tenders;')).toBe('0')
    expect(pg.call('SELECT count(*) FROM public.procurement_tender_audit;')).toBe('3')
  })
  test.each([ids.foreign, ids.inactive, actors.restricted, actors.unlicensed, actors.member])('denies private reads and writes to %s', actor => {
    pg.call(saveTender())
    expect(pg.call('SELECT count(*) FROM public.procurement_tenders;', actor)).toBe('0')
    expect(() => pg.call(saveTender(), actor)).toThrow(/access denied/)
  })
  test('browser roles cannot write tables or bypass policy through materializer', () => {
    const id = pg.call(saveTender())
    expect(() => pg.call('UPDATE public.procurement_tenders SET status=\'published\';')).toThrow(/permission denied/)
    expect(() => pg.call(materialize(id))).toThrow(/permission denied/)
    expect(() => pg.call(materialize(id), ids.owner, 'service_role')).toThrow(/permission denied/)
    expect(() => pg.call('SELECT * FROM public.procurement_tenders;', ids.owner, 'anon')).toThrow(/permission denied/)
    expect(() => pg.db('UPDATE public.procurement_tender_publications SET snapshot=\'{}\'::jsonb;')).toThrow(/immutable/)
    expect(publicRows()).toEqual([])
  })
  test('publications freeze minimal DTO and draft amendments do not change published visibility', () => {
    const id = pg.call(saveTender()); pg.db(materialize(id))
    const first = publicRows()[0]
    expect(first.snapshot).toMatchObject({ title: 'Office equipment', requirements: [{ description: 'Ergonomic chairs', quantity: 5 }] })
    expect(JSON.stringify(first)).not.toMatch(/unit_net_minor|net_amount_minor|created_by|supplier_id|request_id|catalog_item_id/)
    pg.call(saveTender(id, 1, { ...tenderDocument, title: 'Unpublished change', visibility: 'private', global_visible: false }))
    expect(publicRows()[0].snapshot.title).toBe('Office equipment')
    pg.db(materialize(id, 2))
    expect(publicRows()).toEqual([])
    expect(pg.call('SELECT count(*) FROM public.procurement_tender_publications;')).toBe('2')
  })
  test('global opt-in and public/unlisted/private access remain independent', () => {
    const id = pg.call(saveTender(null, 0, { ...tenderDocument, global_visible: false }))
    pg.db(materialize(id))
    const site = pg.call('SELECT slug FROM public.procurement_tender_portals;')
    const slug = pg.call('SELECT portal_slug FROM public.procurement_tenders;')
    expect(publicRows()).toEqual([]); expect(publicRows(site)).toHaveLength(1)
    pg.call(saveTender(id, 1, { ...tenderDocument, visibility: 'unlisted', global_visible: false })); pg.db(materialize(id, 2))
    expect(publicRows(site)).toEqual([]); expect(publicRows(site, slug)).toHaveLength(1)
    expect(publicRows(site, uuid(999))).toEqual([])
    pg.call(`SELECT public.transition_procurement_tender('${ids.site}','${id}',2,'cancel');`)
    expect(publicRows(site, slug)).toEqual([])
  })
  test('publication rejects expired dates, stale versions, unapproved requests and revoked publishers', () => {
    const id = pg.call(saveTender(null, 0, { ...tenderDocument, participation_deadline: '2000-01-01T00:00:00Z' }))
    expect(() => pg.db(materialize(id))).toThrow(/dates expired/)
    expect(() => pg.db(materialize(id, 2))).toThrow(/version conflict/)
    const request = pg.call(saveRequest())
    pg.call(saveTender(id, 1, { ...tenderDocument, request_id: request }))
    expect(() => pg.db(materialize(id, 2))).toThrow(/must be approved/)
    expect(() => pg.db(materialize(id, 2, ids.inactive))).toThrow(/revoked/)
  })
  test('portal and global policy revocation take immediate effect without resurrecting opt-in', () => {
    const id = pg.call(saveTender()); pg.db(materialize(id))
    const site = pg.call('SELECT slug FROM public.procurement_tender_portals;')
    pg.call(`SELECT public.configure_procurement_tender_portal('${ids.site}',false);`)
    expect(publicRows()).toEqual([]); expect(publicRows(site)).toEqual([])
    pg.call(`SELECT public.configure_procurement_tender_portal('${ids.site}',true);`)
    expect(publicRows()).toHaveLength(1)
    pg.call(`SELECT public.save_procurement_policy('${ids.site}',1,'{"version":1,"settings":{"allowGlobalListing":false},"rules":[]}'::jsonb);`)
    expect(publicRows()).toEqual([]); expect(publicRows(site)).toHaveLength(1)
    pg.call(`SELECT public.save_procurement_policy('${ids.site}',2,'{"version":1,"settings":{"allowGlobalListing":true},"rules":[]}'::jsonb);`)
    expect(publicRows()).toEqual([])
    pg.call(saveTender(id, 1)); pg.db(materialize(id, 2)); expect(publicRows()).toHaveLength(1)
  })
  test('on-receipt opening may precede closing and is frozen in published terms', () => {
    const id = pg.call(saveTender(null, 0, { ...tenderDocument, opening_policy: 'on_receipt', opening_at: '2089-01-01T00:00:00Z' }))
    pg.db(materialize(id))
    expect(publicRows()[0].snapshot.opening_policy).toBe('on_receipt')
  })
  test('rejects invalid, overflowing and cross-tenant requirements and links', () => {
    expect(() => pg.call(saveTender(null, 0, { ...tenderDocument, requirements: [{ ...tenderDocument.requirements[0], quantity: null }] }))).toThrow(/Invalid requirement/)
    expect(() => pg.call(saveTender(null, 0, { ...tenderDocument, requirements: [{ ...tenderDocument.requirements[0], unit_net_minor: Number.MAX_SAFE_INTEGER }] }))).toThrow(/Invalid estimate/)
    expect(() => pg.call(saveTender(null, 0, { ...tenderDocument, request_id: uuid(999) }))).toThrow(/access denied/)
    expect(() => pg.call(saveTender(null, 0, { ...tenderDocument, requirements: [{ ...tenderDocument.requirements[0], catalog_item_id: uuid(999) }] }))).toThrow(/access denied/)
  })
  test('only approved same-site suppliers can be invited; withdrawal is audited', () => {
    const id = pg.call(saveTender())
    const invite = (supplier = supplierId, status = 'invited') => `SELECT public.set_procurement_tender_participant('${ids.site}','${id}',1,'${supplier}','${status}');`
    pg.call(invite()); pg.call(invite(supplierId, 'withdrawn'))
    expect(pg.call('SELECT status FROM public.procurement_tender_participants;')).toBe('withdrawn')
    expect(() => pg.call(invite(uuid(802)))).toThrow(/same-site/)
    pg.db(`UPDATE public.suppliers SET status='blocked' WHERE id='${supplierId}';`)
    expect(() => pg.call(invite())).toThrow(/same-site/)
  })
  test('concurrent amendments serialize with only one accepted version', async () => {
    const id = pg.call(saveTender())
    const results = await Promise.allSettled([1, 2].map(() => pg.concurrent(actorSql(`BEGIN; ${saveTender(id, 1)} SELECT pg_sleep(0.1); COMMIT;`, ids.owner))))
    expect(results.filter(row => row.status === 'fulfilled')).toHaveLength(1)
    expect(results.filter(row => row.status === 'rejected')).toHaveLength(1)
  })
})