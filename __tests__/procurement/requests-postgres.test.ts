/** @jest-environment node */
import { actors, ids, isolatedPostgres, postgresAvailable, saveSql, sqlJson, uuid, actorSql } from './storage-fixture'
import { installRequestsFixture, saveRequest, requestDocument, taxId, policyWithStages, planFor, submitRequest, decideRequest } from './requests-fixture'

jest.setTimeout(180000)
const describePg = postgresAvailable ? describe : describe.skip
describePg('purchase requests and approval enforcement in isolated PostgreSQL', () => {
  const pg = isolatedPostgres()
  beforeAll(() => pg.start())
  afterAll(() => pg.stop())
  beforeEach(() => installRequestsFixture(pg))
  const status = (id: string) => pg.call(`SELECT status FROM public.procurement_requests WHERE id='${id}';`)
  const setup = (overrides: Record<string, unknown> = {}) => {
    const document = policyWithStages(overrides)
    const revision = Number(pg.db(`SELECT COALESCE(max(revision),0) FROM public.procurement_policy_versions;`))
    pg.call(saveSql(revision, document))
    const id = pg.call(saveRequest())
    pg.call(submitRequest(id, planFor(document), ids.owner, 1, revision + 1), ids.owner, 'service_role')
    const stage = pg.call(`SELECT id FROM public.procurement_request_stages WHERE request_id='${id}';`)
    return { id, stage }
  }
  test('catalog net prices and taxes are trusted, revision snapshots survive catalog and draft edits', () => {
    const id = pg.call(saveRequest())
    const before = JSON.parse(pg.call(`SELECT row_to_json(i) FROM public.procurement_request_items i WHERE request_id='${id}';`))
    expect(before).toMatchObject({ unit_net_minor: 1234, net_amount_minor: 2468, quantity: 2, revision: 1, tax_snapshot: [{ id: taxId, name: 'VAT', rate: 16 }] })
    pg.db(`UPDATE public.catalog_items SET cost=20; UPDATE public.taxes SET rate=20;`)
    pg.call(saveRequest(id, 1))
    expect(pg.call(`SELECT count(*) FROM public.procurement_request_items WHERE request_id='${id}';`)).toBe('2')
    expect(JSON.parse(pg.call(`SELECT tax_snapshot FROM public.procurement_request_items WHERE request_id='${id}' AND revision=1;`))).toEqual(before.tax_snapshot)
    expect(pg.call(`SELECT net_amount_minor FROM public.procurement_requests WHERE id='${id}';`)).toBe('4000')
    expect(() => pg.call(saveRequest(id, 1))).toThrow(/Revision/)
    expect(() => pg.call(saveRequest(null, 0, { ...requestDocument, lines: [{ ...requestDocument.lines[0], unit_net_minor: 1 }] }))).toThrow(/Invalid line/)
  })
  test.each([ids.foreign, ids.inactive, actors.restricted, actors.unlicensed, actors.member, uuid(999)])('denies request reads and writes for %s', actor => {
    const id = pg.call(saveRequest())
    expect(pg.call(`SELECT count(*) FROM public.procurement_requests;`, actor)).toBe('0')
    expect(() => pg.call(saveRequest(id, 1), actor)).toThrow(/access denied/)
    expect(() => pg.call(saveRequest(), actor)).toThrow(/access denied/)
  })
  test('denies direct table writes and fabricated plan RPC to every arbitrary authenticated user', () => {
    const id = pg.call(saveRequest())
    for (const actor of [ids.owner, ids.admin, actors.member]) {
      expect(() => pg.call(`UPDATE public.procurement_requests SET status='approved' WHERE id='${id}';`, actor)).toThrow(/permission denied/)
      expect(() => pg.call(submitRequest(id, { status: 'ready', stages: [] }), actor)).toThrow(/permission denied/)
    }
    for (const table of ['procurement_request_items', 'procurement_request_stages', 'procurement_request_decisions', 'procurement_request_audit']) {
      expect(() => pg.call(`DELETE FROM public.${table};`)).toThrow(/permission denied/)
      expect(() => pg.call(`SELECT * FROM public.${table};`, ids.owner, 'anon')).toThrow(/permission denied/)
    }
    expect(() => pg.call(submitRequest(id, { status: 'ready', stages: [] }, ids.foreign), ids.owner, 'service_role')).toThrow(/access denied/)
  })
  test('free text services are drafts only; missing policy, unpriced and wrong-currency inputs fail closed', () => {
    const id = pg.call(saveRequest(null, 0, { ...requestDocument, lines: [{ catalog_item_id: null, description: 'Consulting', quantity: 1 }] }))
    expect(status(id)).toBe('draft')
    pg.call(saveSql(0, policyWithStages()))
    expect(() => pg.call(submitRequest(id, planFor(policyWithStages())), ids.owner, 'service_role')).toThrow(/Unresolved/)
    expect(() => pg.call(saveRequest(null, 0, { ...requestDocument, currency: 'MXN' }))).toThrow(/pricing unavailable/)
    pg.db(`UPDATE public.catalog_items SET site_id='${ids.otherSite}';`)
    expect(() => pg.call(saveRequest())).toThrow(/pricing unavailable/)
  })
  test('pins policy revision and requires all distinct votes, preserving decisions and audit', () => {
    const { id, stage } = setup()
    pg.call(saveSql(1, policyWithStages({ quorum: { mode: 'first_response' } })))
    expect(status(id)).toBe('submitted')
    pg.call(decideRequest(id, stage), ids.admin)
    expect(status(id)).toBe('submitted')
    expect(() => pg.call(decideRequest(id, stage), ids.admin)).toThrow(/duplicate key/)
    pg.call(decideRequest(id, stage), ids.owner)
    expect(status(id)).toBe('approved')
    expect(pg.call(`SELECT policy_revision FROM public.procurement_requests WHERE id='${id}';`)).toBe('1')
    expect(pg.call(`SELECT count(*) FROM public.procurement_request_audit WHERE request_id='${id}';`)).toBe('4')
    expect(() => pg.call(saveRequest(id, 1))).toThrow(/state conflict/)
  })
  test('manager service estimates use integer budgets and explicit same-site tax rates, never client rates', () => {
    const line = { catalog_item_id: null, description: 'Consulting budget', quantity: 3, unit_estimate_minor: 5001, tax_ids: [taxId] }
    const id = pg.call(saveRequest(null, 0, { ...requestDocument, lines: [line] }))
    const item = JSON.parse(pg.call(`SELECT row_to_json(i) FROM public.procurement_request_items i WHERE request_id='${id}';`))
    expect(item).toMatchObject({ valuation_source: 'manager_estimate', unit_net_minor: 5001, net_amount_minor: 15003, tax_snapshot: [{ rate: 16 }] })
    const policy = policyWithStages({ quorum: { mode: 'first_response' } })
    pg.call(saveSql(0, policy))
    pg.call(submitRequest(id, planFor(policy)), ids.owner, 'service_role')
    const stage = pg.call(`SELECT id FROM public.procurement_request_stages WHERE request_id='${id}';`)
    pg.call(decideRequest(id, stage), ids.admin)
    expect(status(id)).toBe('approved')
    expect(() => pg.call(saveRequest(null, 0, { ...requestDocument, lines: [{ ...line, unit_estimate_minor: 1.5 }] }))).toThrow(/estimate/)
    expect(() => pg.call(saveRequest(null, 0, { ...requestDocument, lines: [{ ...line, tax_ids: undefined }] }))).toThrow(/tax selection/)
    expect(() => pg.call(saveRequest(null, 0, { ...requestDocument, lines: [{ ...line, tax_rate: 0 }] }))).toThrow(/Invalid line/)
    expect(() => pg.call(saveRequest(null, 0, { ...requestDocument, lines: [{ ...line, tax_ids: [uuid(999)] }] }))).toThrow(/tax selection/)
    pg.db(`UPDATE public.taxes SET site_id='${ids.otherSite}';`)
    expect(() => pg.call(saveRequest(null, 0, { ...requestDocument, lines: [line] }))).toThrow(/tax selection/)
    const explicitNone = pg.call(saveRequest(null, 0, { ...requestDocument, lines: [{ ...line, tax_ids: [] }] }))
    expect(pg.call(`SELECT tax_snapshot FROM public.procurement_request_items WHERE request_id='${explicitNone}';`)).toBe('[]')
  })
  test.each(['ai_assisted', 'automatic_ai'])('%s remains pending and cannot be satisfied by a human click', mode => {
    const { id, stage } = setup(mode === 'automatic_ai' ? { decisionMode: mode, approverIds: [], quorum: { mode: 'first_response' }, delegatedAgentId: uuid(500) } : { decisionMode: mode })
    expect(() => pg.call(decideRequest(id, stage), ids.admin)).toThrow(/pending AI/)
    expect(status(id)).toBe('submitted')
  })
  test('first-response, N-of-M, mandatory and rejection/return semantics are real', () => {
    const { id, stage } = setup({ quorum: { mode: 'first_response' }, mandatoryApproverIds: [ids.owner], rejectionBehavior: 'return_for_correction' })
    pg.call(decideRequest(id, stage), ids.admin)
    expect(status(id)).toBe('submitted')
    pg.call(decideRequest(id, stage, 'reject'))
    expect(status(id)).toBe('returned')
    pg.call(saveRequest(id, 1))
    expect(status(id)).toBe('draft')
    expect(pg.call(`SELECT count(*) FROM public.procurement_request_decisions;`)).toBe('2')
    const second = setup({ quorum: { mode: 'n_of_m', count: 1 }, rejectionBehavior: 'failed_vote' })
    pg.call(decideRequest(second.id, second.stage, 'reject'), ids.admin)
    expect(status(second.id)).toBe('submitted')
    pg.call(decideRequest(second.id, second.stage))
    expect(status(second.id)).toBe('approved')
  })
  test('revoked access and expired deadlines never grant approval', () => {
    const { id, stage } = setup()
    pg.db(`UPDATE public.fixture_members SET active=false WHERE user_id='${ids.admin}';`)
    expect(() => pg.call(decideRequest(id, stage), ids.admin)).toThrow(/access denied/)
    pg.db(`UPDATE public.procurement_request_stages SET definition=jsonb_set(definition,'{resolvedDeadline}',${sqlJson('2000-01-01T00:00:00Z')});`)
    expect(() => pg.call(decideRequest(id, stage))).toThrow(/Deadline reached/)
    expect(status(id)).toBe('submitted')
  })
  test('rejects stale submission plans after policy changes', () => {
    const document = policyWithStages(); pg.call(saveSql(0, document)); const id = pg.call(saveRequest())
    pg.call(saveSql(1, document))
    expect(() => pg.call(submitRequest(id, planFor(document)), ids.owner, 'service_role')).toThrow(/Policy revision conflict/)
    expect(status(id)).toBe('draft')
  })
  test('active named members can see and decide assigned requests but cannot edit drafts or see other requests', () => {
    const { id, stage } = setup({ approverIds: [actors.member], quorum: { mode: 'first_response' }, allowSelfApproval: false })
    pg.call(saveRequest())
    expect(pg.call(`SELECT count(*) FROM public.procurement_requests;`, actors.member)).toBe('1')
    expect(pg.call(`SELECT count(*) FROM public.procurement_request_stages;`, actors.member)).toBe('1')
    expect(() => pg.call(saveRequest(), actors.member)).toThrow(/access denied/)
    pg.call(decideRequest(id, stage), actors.member)
    expect(status(id)).toBe('approved')
  })
  test('sequential stage order and forbidden self-approval are enforced independently of the UI', () => {
    const document = policyWithStages({ quorum: { mode: 'first_response' } })
    if (document.settings.fallback.mode !== 'approval') throw new Error('Expected approval policy')
    document.settings.fallback.stages.push({ ...document.settings.fallback.stages[0], id: 'second', name: 'Second review', execution: 'sequential', allowSelfApproval: false, approverIds: [ids.admin] })
    pg.call(saveSql(0, document)); const id = pg.call(saveRequest())
    pg.call(submitRequest(id, planFor(document)), ids.owner, 'service_role')
    const stages = JSON.parse(pg.call(`SELECT jsonb_agg(id ORDER BY position) FROM public.procurement_request_stages;`))
    expect(() => pg.call(decideRequest(id, stages[1]), ids.admin)).toThrow(/Earlier stage/)
    expect(() => pg.call(decideRequest(id, stages[1]))).toThrow(/Ineligible/)
    pg.call(decideRequest(id, stages[0]))
    expect(status(id)).toBe('submitted')
    pg.call(decideRequest(id, stages[1]), ids.admin)
    expect(status(id)).toBe('approved')
  })
  test('independent rule groups cannot reuse a vote and unrelated sequential groups are not serialized', () => {
    const document = policyWithStages({ quorum: { mode: 'first_response' } })
    const plan = planFor(document)
    plan.stages = [
      { ...plan.stages[0], sourceRuleId: 'rule-a', sourceRuleVersion: 1 },
      { ...plan.stages[0], id: 'second', sourceRuleId: 'rule-b', sourceRuleVersion: 1, execution: 'sequential' },
    ]
    pg.call(saveSql(0, document)); const id = pg.call(saveRequest())
    pg.call(submitRequest(id, plan), ids.owner, 'service_role')
    const stages = JSON.parse(pg.call(`SELECT jsonb_agg(id ORDER BY position) FROM public.procurement_request_stages;`))
    pg.call(decideRequest(id, stages[1]), ids.admin)
    expect(() => pg.call(decideRequest(id, stages[0]), ids.admin)).toThrow(/Independent rules/)
    pg.call(decideRequest(id, stages[0]), ids.owner)
    expect(status(id)).toBe('approved')
  })
  test('category and tax tenant mismatches fail closed inside draft RPC', () => {
    const category = uuid(700)
    pg.db(`INSERT INTO public.catalog_categories VALUES('${category}','${ids.otherSite}','active');
      UPDATE public.catalog_items SET category_id='${category}';`)
    expect(() => pg.call(saveRequest())).toThrow(/classification unavailable/)
    pg.db(`UPDATE public.catalog_items SET category_id=NULL; UPDATE public.taxes SET site_id='${ids.otherSite}';`)
    expect(() => pg.call(saveRequest())).toThrow(/taxes unavailable/)
  })
  test('serializes concurrent first responses; no double approval or rejection overwrite', async () => {
    const { id, stage } = setup({ quorum: { mode: 'first_response' } })
    const results = await Promise.allSettled([ids.admin, ids.owner].map(actor => pg.concurrent(actorSql(`BEGIN; ${decideRequest(id, stage)} SELECT pg_sleep(0.1); COMMIT;`, actor))))
    expect(results.filter(result => result.status === 'fulfilled')).toHaveLength(1)
    expect(results.filter(result => result.status === 'rejected')).toHaveLength(1)
    expect(status(id)).toBe('approved')
    expect(pg.call(`SELECT count(*) FROM public.procurement_request_decisions;`)).toBe('1')
  })
})